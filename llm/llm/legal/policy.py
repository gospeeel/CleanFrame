def calculate_simple_rating(category: str, level: int) -> str:
    return calculate_rating(category, level)


def get_policy_entry(category: str) -> dict:
    normalized = normalize_category(category)
    return LEGAL_POLICY.get(normalized, {
        "basis": "ФЗ-436: потенциально рискованный контент требует экспертной оценки.",
        "fallback": (
            "Рекомендуется смягчить сцену, исключив элементы, которые могут быть расценены как насилие, "
            "ненормативная лексика, эротика, употребление веществ или пугающие сцены."
        ),
    })


def fallback_recommendation(
    category: str,
    level: int,
    target_rating: str | None = None,
    element_type: str = "action",
    character: str = "",
) -> str:
    entry = get_policy_entry(category)
    rec = entry["fallback"]
    rec += f"\n\nОснование: {entry['basis']} Уровень риска: {level}."
    if target_rating:
        rec += f"\n\nЦель правки: снизить сцену до {target_rating} или ниже без потери сюжетной функции."

    if element_type == "dialogue" and character:
        rec += f"\n\nПримечание: рекомендация относится к реплике персонажа «{character}»."

    return rec
