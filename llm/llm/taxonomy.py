def normalize_category(category: str | None) -> str:
    if not category:
        return "safe"
    return CATEGORY_ALIASES.get(str(category), str(category))


def category_label(category: str | None) -> str:
    normalized = normalize_category(category)
    return CATEGORY_LABELS.get(normalized, str(category or "Без риска"))


def level_label(level: int | None) -> str:
    if level is None:
        return "уровень не определён"
    return LEVEL_LABELS.get(int(level), f"уровень {level}")


def dedupe_categories(categories: list[str]) -> list[str]:
    result = []
    seen = set()
    for category in categories:
        normalized = normalize_category(category)
        if normalized not in seen:
            seen.add(normalized)
            result.append(normalized)
    return result


def score_curated_terms(text: str) -> tuple[dict[str, float], dict[str, list[str]]]:
    lowered = text.lower()
    scores = {category: 0.0 for category in CURATED_TERMS}
    matches = {category: [] for category in CURATED_TERMS}

    for category, terms in CURATED_TERMS.items():
        for term, weight in terms.items():
            if _term_found(lowered, term):
                scores[category] += weight
                matches[category].append(term)

    for category in set(SAFE_CONTEXT_PATTERNS) | set(SAFE_CONTEXT_REGEXES):
        if safe_context_matches_category(lowered, category):
            scores[category] = 0.0
            matches[category] = []

    return scores, matches


def safe_context_categories(text: str) -> set[str]:
    lowered = text.lower()
    return {
        category
        for category in set(SAFE_CONTEXT_PATTERNS) | set(SAFE_CONTEXT_REGEXES)
        if safe_context_matches_category(lowered, category)
    }


def safe_context_matches_category(lowered_text: str, category: str) -> bool:
    return (
        any(pattern in lowered_text for pattern in SAFE_CONTEXT_PATTERNS.get(category, []))
        or any(re.search(pattern, lowered_text) for pattern in SAFE_CONTEXT_REGEXES.get(category, []))
    )


def ambiguous_context_adjustments(text: str) -> dict[str, dict | set]:
    lowered = text.lower()
    suppress: set[str] = set()
    boosts: dict[str, float] = {}
    matches: dict[str, list[str]] = {}

    bloodshot = AMBIGUOUS_CONTEXT_RULES["bloodshot_eyes"]
    if any(re.search(pattern, lowered) for pattern in bloodshot["regexes"]):
        has_injury_context = any(term in lowered for term in bloodshot["injury_terms"])
        if not has_injury_context:
            suppress.update(bloodshot["suppress"])
            if not any(term in lowered for term in bloodshot["safe_causes"]):
                for category, score in bloodshot["boosts"].items():
                    boosts[category] = max(boosts.get(category, 0.0), float(score))
                    matches.setdefault(category, []).append("глаза налиты кровью")

    for rule_name in ("fear_idioms_with_blood_or_body",):
        rule = AMBIGUOUS_CONTEXT_RULES[rule_name]
        if any(pattern in lowered for pattern in rule.get("matches", ())):
            matched = next(pattern for pattern in rule.get("matches", ()) if pattern in lowered)
        else:
            matched = next(
                (
                    readable
                    for regex, readable in zip(rule.get("regexes", ()), rule.get("matches", ()))
                    if re.search(regex, lowered)
                ),
                None,
            )
        if not matched:
            continue

        suppress.update(rule.get("suppress", set()))
        for category, score in rule.get("boosts", {}).items():
            boosts[category] = max(boosts.get(category, 0.0), float(score))
            matches.setdefault(category, []).append(str(matched))

    return {
        "suppress": suppress,
        "boosts": boosts,
        "matches": matches,
    }


def _term_found(text: str, term: str) -> bool:
    escaped = re.escape(term.lower())
    if " " in term:
        return re.search(rf"(?<!\w){escaped}(?!\w)", text) is not None
    return re.search(rf"(?<!\w){escaped}\w*(?!\w)", text) is not None


def evidence_items(text: str, matched_terms: dict[str, list[str]]) -> list[dict[str, str]]:
    items = []
    lowered = text.lower()
    for category, terms in matched_terms.items():
        normalized = normalize_category(category)
        for term in terms:
            snippet = _evidence_snippet(text, lowered, term)
            items.append({
                "category": normalized,
                "category_label": category_label(normalized),
                "text": snippet or term,
                "matched_term": term,
                "reason": EVIDENCE_REASONS.get(normalized, "потенциальный фактор риска"),
            })
    return items


def _evidence_snippet(original: str, lowered: str, term: str) -> str:
    match = re.search(rf"(?<!\w){re.escape(term.lower())}\w*(?!\w)", lowered)
    if not match:
        return term

    sentences = _split_sentences_with_spans(original)
    selected = _sentence_window_for_match(sentences, match.start(), match.end(), max_sentences=2)
    if selected:
        return " ".join(sentence.strip() for sentence, _start, _end in selected).strip(" .,;:!?")

    start = max(0, match.start() - 80)
    end = min(len(original), match.end() + 80)
    return original[start:end].strip(" .,;:!?")


def _split_sentences_with_spans(text: str) -> list[tuple[str, int, int]]:
    spans: list[tuple[str, int, int]] = []
    start = 0
    for match in re.finditer(r"(?<=[.!?\u2026])\s+", text):
        end = match.start()
        sentence = text[start:end].strip()
        if sentence:
            spans.append((sentence, start, end))
        start = match.end()

    tail = text[start:].strip()
    if tail:
        spans.append((tail, start, len(text)))
    return spans or [(text.strip(), 0, len(text))]


def _sentence_window_for_match(
    sentences: list[tuple[str, int, int]],
    match_start: int,
    match_end: int,
    max_sentences: int,
) -> list[tuple[str, int, int]]:
    if not sentences:
        return []

    index = 0
    for i, (_sentence, start, end) in enumerate(sentences):
        if start <= match_start and match_end <= end:
            index = i
            break

    left = max(0, index - 1)
    right = min(len(sentences), left + max_sentences)
    if index >= right:
        right = min(len(sentences), index + 1)
        left = max(0, right - max_sentences)
    return sentences[left:right]


def primary_category_from_evidence(predicted_category: str, natasha: dict) -> tuple[str, list[str]]:
    predicted = normalize_category(predicted_category)
    flags = natasha.get("flags", {}) if isinstance(natasha, dict) else {}
    normalized_flags = natasha.get("normalized_flags", {}) if isinstance(natasha, dict) else {}
    scores = natasha.get("category_scores", {}) if isinstance(natasha, dict) else {}

    active = [
        normalize_category(category)
        for category, is_active in flags.items()
        if is_active
    ]
    active.extend(
        normalize_category(category)
        for category, is_active in normalized_flags.items()
        if is_active
    )
    active = dedupe_categories(active)
    if not active:
        return predicted, []

    def sort_key(category: str) -> tuple[float, int]:
        score = float(scores.get(category, 0.0))
        return score, CATEGORY_PRIORITY.get(category, 0)

    primary = max(active, key=sort_key)
    if predicted in active and float(scores.get(predicted, 0.0)) >= float(scores.get(primary, 0.0)):
        primary = predicted

    secondary = [category for category in active if category != primary]
    return primary, secondary
