def build_recommendation_context(
    item_id: str,
    text: str,
    category: str,
    category_label: str | None,
    secondary_categories: list[str] | None,
    level: int,
    level_label: str | None,
    rating: str,
    target_rating: str,
    evidence: list[dict] | None,
    confidence: dict,
    needs_review: bool,
    element_type: str = "action",
    character: str = "",
) -> dict:
    normalized_category = normalize_category(category)
    readable_category = category_label or get_category_label(normalized_category)
    legal_context = retrieve_legal_context(
        category=normalized_category,
        level=level,
        rating=rating,
        text=text,
        evidence=evidence or [],
    )
    recommendation_text = fallback_recommendation(
        category=normalized_category,
        level=level,
        target_rating=target_rating,
        element_type=element_type,
        character=character,
    )
    payload = build_policy_payload(
        text=text,
        recommendation_text=recommendation_text,
        category=normalized_category,
        category_label=readable_category,
        target_rating=target_rating,
        evidence=evidence or [],
    )
    return {
        "id": item_id,
        "text": text,
        "category": normalized_category,
        "category_label": readable_category,
        "secondary_categories": secondary_categories or [],
        "secondary_labels": [get_category_label(item) for item in (secondary_categories or [])],
        "level": level,
        "level_label": level_label,
        "rating": rating,
        "target_rating": target_rating,
        "evidence": evidence or [],
        "confidence": confidence,
        "needs_review": needs_review,
        "element_type": element_type,
        "character": character,
        "legal_context": legal_context,
        "policy_basis": get_policy_entry(normalized_category)["basis"],
        "policy_text": recommendation_text,
        "policy_payload": payload,
    }


def generate_recommendation_packages_batch(contexts: list[dict]) -> dict[str, dict]:
    return {context["id"]: package_from_context(context) for context in contexts}


def package_from_context(context: dict) -> dict:
    payload = context["policy_payload"]
    return {
        "text": format_recommendation_text(payload),
        "recommendation": {
            "summary": payload["summary"],
            "rewrite_suggestions": payload["rewrite_suggestions"],
            "fallback_used": False,
            "self_check_passed": True,
            "grouped_recommendation_id": None,
            "grouped_recommendation_ids": [context["id"]],
        },
        "llm_recommendation": payload,
        "fallback_used": False,
        "fallback_reason": None,
        "llm_error": None,
        "legal_context": context["legal_context"],
        "policy_basis": context["policy_basis"],
        "grouped_recommendation_id": None,
        "grouped_recommendation_ids": [context["id"]],
    }


def build_policy_payload(
    text: str,
    recommendation_text: str,
    category: str,
    category_label: str,
    target_rating: str,
    evidence: list[dict],
) -> dict:
    before = evidence[0].get("text", "") if evidence else _shorten(text, 180)
    before = before or _shorten(text, 180)
    risk_factors = [
        str(item.get("text", "")).strip()
        for item in evidence[:4]
        if isinstance(item, dict) and str(item.get("text", "")).strip()
    ]
    if not risk_factors:
        risk_factors = [_shorten(text, 180)] if text else []

    explanation = CATEGORY_EXPLANATIONS.get(category, recommendation_text)
    return {
        "summary": f"{category_label}: правка для целевого рейтинга {target_rating}.",
        "explanation": f"{category_label}. {explanation}",
        "risk_factors": risk_factors,
        "rewrite_suggestions": build_rewrite_suggestions(
            category=category,
            before=before,
            text=text,
            evidence=evidence,
            target_rating=target_rating,
        ),
        "self_check_passed": True,
        "uncertainty_note": None,
        "source": "policy",
    }


def build_rewrite_suggestions(
    category: str,
    before: str,
    text: str,
    evidence: list[dict],
    target_rating: str,
) -> list[dict]:
    normalized = normalize_category(category)
    bank = REWRITE_BANK.get(normalized, REWRITE_BANK["violence"])
    seed = stable_seed(normalized, text, evidence)
    suggestions = []
    for offset, goal in enumerate(GOALS):
        options = bank[goal]
        after, rationale, expected_effect = options[(seed + offset * 3) % len(options)]
        suggestions.append({
            "goal": goal,
            "before": before,
            "after": after.format(target=target_rating),
            "rationale": rationale.format(target=target_rating),
            "expected_effect": expected_effect.format(target=target_rating),
        })
    return suggestions


def stable_seed(category: str, text: str, evidence: list[dict]) -> int:
    evidence_terms = "|".join(
        str(item.get("matched_term", ""))
        for item in evidence
        if isinstance(item, dict)
    )
    raw = f"{category}|{text}|{evidence_terms}".encode("utf-8", errors="ignore")
    return int(hashlib.sha256(raw).hexdigest()[:8], 16)


def format_recommendation_text(payload: dict) -> str:
    parts = [str(payload.get("explanation", "")).strip()]
    risk_factors = [
        str(item).strip()
        for item in payload.get("risk_factors", [])
        if str(item).strip()
    ]
    suggestions = [
        item for item in payload.get("rewrite_suggestions", [])
        if isinstance(item, (str, dict))
    ]

    if risk_factors:
        parts.append("Факторы риска:\n" + "\n".join(f"- {item}" for item in risk_factors))
    if suggestions:
        parts.append("Редакционные правки:\n" + "\n".join(format_suggestion(item) for item in suggestions))

    return "\n\n".join(part for part in parts if part)


def format_suggestion(item: str | dict) -> str:
    if isinstance(item, str):
        return f"- {item}"
    return (
        f"- {item.get('goal', 'Правка')}\n"
        f"  Что изменить: {str(item.get('after', '')).strip()}\n"
        f"  Почему: {str(item.get('rationale', '')).strip()}\n"
        f"  Эффект: {str(item.get('expected_effect', '')).strip()}"
    )


def _shorten(text: str, limit: int) -> str:
    text = " ".join(str(text).split())
    if len(text) <= limit:
        return text
    return text[: limit - 3].rstrip() + "..."
