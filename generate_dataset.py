TIMES = [
    "утром", "вечером", "ночью", "после обеда", "на рассвете", "перед сном"
]

def scene(prefix, text):
    """Генерация небольших мини-сцен"""
    name1 = fake.first_name()
    name2 = fake.first_name()
    location = random.choice(LOCATIONS)
    time = random.choice(TIMES)

    return f"{prefix} {time} {location}: {name1} {text} {name2 if '{}' in text else ''}".replace("  ", " ").strip()


